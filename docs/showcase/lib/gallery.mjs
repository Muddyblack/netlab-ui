// Markdown for the gallery: a thumbnail grid of every feature, then one
// collapsible section per feature with all its stills (light/dark via
// <picture>) and its animated preview. Written to docs/showcase/GALLERY.md;
// the repository README gets just the grid (between showcase markers), each
// thumbnail linking to its section in GALLERY.md.

import fs from "node:fs";

const START = "<!-- showcase:start -->";
const END = "<!-- showcase:end -->";

function picture(prefix, files, alt, width) {
  const light = files.light ?? files.dark;
  const dark = files.dark ?? files.light;
  const size = width ? ` width="${width}"` : "";
  if (light === dark) return `<img src="${prefix}${light}" alt="${alt}"${size} />`;
  return [
    "<picture>",
    `  <source media="(prefers-color-scheme: dark)" srcset="${prefix}${dark}" />`,
    `  <img src="${prefix}${light}" alt="${alt}"${size} />`,
    "</picture>",
  ].join("\n");
}

/**
 * `prefix` is the path from the markdown file to docs/showcase/media/.
 * `details: false` leaves out the per-feature sections; thumbnails then link
 * to `linkBase` (the GALLERY.md holding them).
 */
export function galleryMarkdown(manifest, prefix, { columns = 2, details = true, linkBase = "", excludeFeatureIds = [] } = {}) {
  const features = manifest.features.filter((feature) =>
    !excludeFeatureIds.includes(feature.id) && feature.shots.some((shot) => Object.keys(shot.files).length),
  );
  const out = [];
  // Videos are local outputs, so repository galleries link only to committed images.

  out.push("<table>");
  for (let row = 0; row < features.length; row += columns) {
    out.push("<tr>");
    for (const feature of features.slice(row, row + columns)) {
      const hero = feature.shots.find((shot) => shot.hero) ?? feature.shots.find((shot) => shot.window) ?? feature.shots[0];
      out.push(
        `<td width="${Math.floor(100 / columns)}%" valign="top">`,
        `<a href="${linkBase}#showcase-${feature.id}">`,
        picture(prefix, hero.files, hero.alt),
        "</a>",
        `<p><b>${feature.title}</b><br />${feature.summary}</p>`,
        "</td>",
      );
    }
    out.push("</tr>");
  }
  out.push("</table>", "");
  if (!details) return out.join("\n");

  for (const feature of features) {
    out.push(
      `<details id="showcase-${feature.id}">`,
      `<summary><b>${feature.title}</b> — ${feature.summary}</summary>`,
      "",
    );
    for (const shot of feature.shots) {
      if (!Object.keys(shot.files).length) continue;
      out.push(picture(prefix, shot.files, shot.alt, 900), "");
    }
    if (feature.preview) {
      out.push(`<img src="${prefix}${feature.preview}" alt="${feature.title} (animated)" width="900" />`, "");
    }
    out.push("</details>", "");
  }
  out.push(`<sub>Generated by <code>docs/showcase/run.sh</code> on ${manifest.generated.slice(0, 10)} — rerun it after UI changes.</sub>`);
  return out.join("\n");
}

export function writeGallery(manifest, galleryFile, readmeFile) {
  const header = [
    "# netlab-ui showcase",
    "",
    "Screenshots and videos generated from the running app by [`run.sh`](run.sh). See [README](README.md) for how to regenerate or add a feature.",
    "",
  ].join("\n");
  fs.writeFileSync(galleryFile, `${header}\n${galleryMarkdown(manifest, "media/")}\n`);

  if (!readmeFile || !fs.existsSync(readmeFile)) return false;
  const readme = fs.readFileSync(readmeFile, "utf8");
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) return false;
  const body = galleryMarkdown(manifest, "docs/showcase/media/", {
    details: false,
    linkBase: "docs/showcase/GALLERY.md",
    excludeFeatureIds: ["traffic"], // The README hero already shows this screenshot.
  });
  fs.writeFileSync(readmeFile, `${readme.slice(0, start + START.length)}\n${body}\n${readme.slice(end)}`);
  return true;
}
