def builtin_yaml() -> str:
    header = "# Built-in rules, regenerated by the monitoring plugin. Add your own in ../alerts/\n"
    return header + yaml.safe_dump(BUILTIN, sort_keys=False, width=140)


def check(text: str) -> tuple[list[str], list[str]]:
    """Validate a rule file. Returns (errors, warnings); an error means vmalert would reject it."""
    try:
        doc = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        return [f"not valid YAML: {exc}"], []
    groups = doc.get("groups") if isinstance(doc, dict) else None
    if not isinstance(groups, list) or not groups:
        return ["needs a top-level 'groups' list"], []
    errors: list[str] = []
    warns: list[str] = []
    for g, group in enumerate(groups, 1):
        rules = group.get("rules") if isinstance(group, dict) else None
        if not isinstance(group, dict) or not group.get("name") or not isinstance(rules, list):
            errors.append(f"group {g}: needs 'name' and a 'rules' list")
            continue
        for r, rule in enumerate(rules, 1):
            where = f"{group['name']} rule {r}"
            if not isinstance(rule, dict) or not (rule.get("alert") or rule.get("record")):
                errors.append(f"{where}: needs 'alert' (name) or 'record' (name)")
            elif not rule.get("expr"):
                errors.append(f"{where}: needs 'expr'")
            else:
                warns += [
                    f"{where}: unknown metric {m}" for m in catalog.unknown_metrics(typing.cast(str, rule["expr"]))
                ]
    return errors, warns
