"""Alert rules: the built-in ones, and a check for user rule files.

Rules are plain Prometheus/vmalert rule files. The built-in file is regenerated by the
plugin; users add their own as ``<lab>/monitoring/alerts/*.yml`` (reloaded within seconds,
no restart). vmalert writes ``ALERTS`` back to the TSDB, so firing alerts can be queried and
graphed like any metric.
"""

from __future__ import annotations

import typing

import yaml

from . import catalog


def _rule(alert: str, expr: str, summary: str, severity: str = "critical", wait: str = "1m") -> dict:
    return {
        "alert": alert,
        "expr": expr,
        "for": wait,
        "labels": {"severity": severity},
        "annotations": {"summary": summary},
    }


